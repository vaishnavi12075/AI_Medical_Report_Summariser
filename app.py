import streamlit as st
from llm import generate_summary
from pypdf import PdfReader
import re
from fpdf import FPDF

st.set_page_config(
    page_title="AI Medical Report Summariser",
    layout="wide",
    initial_sidebar_state="expanded"
)
def extract_summary(summary,heading):
    pattern = rf"##\s*{re.escape(heading)}\s*(.*?)(?=##|$)"
    match=re.search(pattern,summary,re.DOTALL)
    if match:
        return match.group(1).strip()
    return "Not available."
def extract_medicines(summary):
    medicines = []

    parts = summary.split("MEDICINE:")

    for part in parts[1:]:
        medicine = part.strip()

        # Stop if the next section starts
        medicine = medicine.split("##")[0].strip()

        medicines.append(medicine)

    return medicines

def highlight_abnormal_values(text):
    keywords=[
        "high","low","elevated","increased","decreased","positive","negative","abnormal","deficient"
    ]
    findings=[]
    for line in text.splitlines():
        for keyword in keywords:
            if re.search(rf"\b{keyword}\b",line,re.IGNORECASE):
                findings.append(line.strip())
                break;
    return findings
def create_pdf(summary):
    pdf=FPDF()
    pdf.add_page()
    pdf.set_font("Arial","B",16)
    pdf.cell(0,10,"AI_Medical_Report_Summary",ln=True)
    pdf.ln(5)
    pdf.set_font("Arial",size=12)

    summary=summary.encode("latin-1","replace").decode("latin-1")
    pdf.multi_cell(0,10,summary)
    pdf.output("summary.pdf")




